-- Run once in Supabase SQL Editor. Uses the same authenticated admin access as okp_expenses.
create table if not exists public.okp_member_reimbursements (
 id bigint generated by default as identity primary key,
 expense_date date not null default current_date,
 category text not null,
 description text not null,
 amount numeric(12,2) not null check(amount>0),
 paid_by text not null check(length(trim(paid_by))>0),
 settled_at timestamptz,
 settled_via text check(settled_via in ('Cash','Bank Transfer','Ziina','Other')),
 created_at timestamptz not null default now(),
 constraint reimbursement_settlement_pair check ((settled_at is null and settled_via is null) or (settled_at is not null and settled_via is not null))
);
alter table public.okp_member_reimbursements enable row level security;
drop policy if exists "authenticated member reimbursements" on public.okp_member_reimbursements;
create policy "authenticated member reimbursements" on public.okp_member_reimbursements for all to authenticated using (true) with check (true);
grant select,insert,update,delete on public.okp_member_reimbursements to authenticated;
grant usage,select on all sequences in schema public to authenticated;
